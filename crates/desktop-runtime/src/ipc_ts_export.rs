//! IPC 型の TypeScript 生成(WP-H7 PR3。`ts` feature 時のみ)。
//!
//! 生成器は client 依存グラフの頂点である desktop-runtime に置く。ここからは
//! app-api(views)/ core / store / transport / cn-protocol / 自 crate の
//! community-node 型まで全 IPC 型に到達できる。
//!
//! `cargo test -p kukuri-desktop-runtime --features ts export_ipc_types` で
//! `apps/desktop/src/lib/api/types.generated.ts` を再生成する。xtask `ipc-types`
//! が `TS_RS_LARGE_INT=number` を設定して実行し、CI は再生成後の
//! `git diff --exit-code` で Rust と TS の乖離を検出する。
//!
//! 入力方向の request DTO(requests.rs)も生成対象(WP-B6)。runtimeApi.ts の
//! request 構築 literal は生成型への `satisfies` 注釈で拘束され、Rust 側の変更は
//! 再生成 diff + tsc の二重で検出される。front 専用型(展開引数の便宜型 /
//! エラー型 / DesktopApi interface)は手書きの types.ts 側に残す。
#![cfg(feature = "ts")]

use ts_rs::TS;

const HEADER: &str = "// @generated by `cargo xtask ipc-types` from Rust IPC types. DO NOT EDIT.\n\
// 手で編集せず、Rust 側(crates/app-api/src/views.rs ほか)を変更して再生成すること。\n\n";

fn emit<T: TS>(cfg: &ts_rs::Config, out: &mut String) {
    out.push_str("export ");
    out.push_str(<T as TS>::decl(cfg).trim_end_matches(';'));
    out.push_str(";\n\n");
}

